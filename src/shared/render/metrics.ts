/**
 * Размеры вида шара и схваченного шара. Общие для всех режимов: их читают и рисование шаров, и камера (запас кадра),
 * и ввод (в какой клетке палец).
 */
export const RADIUS = 0.46;
/** Насколько схваченный шар приподнят к зрителю. */
export const HELD_LIFT = 0.6;
export const HELD_SCALE = 1.16;
/** Палец считается «в клетке», если ближе этого к её центру: углы клеток не дёргают шар по диагонали. */
export const CELL_ZONE = 0.62;
/** Центр схваченного шара не уходит от края поля ближе этого: часть шара выступает за поле. */
export const HOLD_INSET = 0.3;
/** Запас на то, что приподнятый к камере шар выглядит крупнее (перспектива). */
const PERSPECTIVE_ALLOWANCE = 0.12;
/**
 * Насколько схваченный шар в крайней клетке выступает за край поля. Камера оставляет такой запас кадра, иначе
 * шар у границы обрезался бы холстом.
 */
export const HELD_OVERHANG = RADIUS * HELD_SCALE - HOLD_INSET + PERSPECTIVE_ALLOWANCE;
